-- 在 Supabase SQL Editor 里执行一次
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  score int not null check (score >= 0 and score <= 5000000),
  grade text not null default 'D',
  hero text not null default '匿名',
  mode text not null default 'story',
  time int not null default 0,
  name text not null default '匿名大学生',
  created_at timestamptz not null default now()
);

alter table public.scores enable row level security;

create policy "anyone can read scores"
on public.scores for select
to anon
using (true);

create policy "anyone can insert scores"
on public.scores for insert
to anon
with check (
  score >= 0 and score <= 5000000
  and length(coalesce(name, '')) <= 20
  and length(coalesce(hero, '')) <= 40
);

-- 可选：只保留最近 500 条，避免无限增长
create or replace function public.trim_scores() returns trigger
language plpgsql security definer as $$
begin
  delete from public.scores where id not in (
    select id from public.scores order by score desc, created_at desc limit 500
  );
  return null;
end $$;

drop trigger if exists trim_scores_after_insert on public.scores;
create trigger trim_scores_after_insert
after insert on public.scores
for each statement execute function public.trim_scores();
